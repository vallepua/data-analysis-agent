# agent/reporter.py
"""Builds the decision-oriented report (Markdown) and the PDF."""
import os
import re

from fpdf import FPDF

from agent.stats_engine import fmt_p, g, sg


# --------------------------------------------------------------------------- Markdown report
def assemble_report(facts, sections, verification, goal="", extra_note=""):
    ds = facts["dataset"]
    t = facts.get("target")
    q = facts["profile"]
    L = []
    L.append(f"**Dataset:** {ds['name']} ({ds['rows']} rows x {ds['cols']} columns)  ")
    if goal:
        L.append(f"**Your goal / decision:** {goal}  ")
    if t:
        L.append(f"**Outcome analysed:** {t['name']} ({t['source']})")
    L.append("")

    L.append("## 1. Executive Summary")
    L.append(sections["summary"])
    L.append("")

    L.append("## 2. Can You Trust This Data?")
    L.append(f"**Verdict: {q['verdict']}** (quality score {q['score']}/100)")
    for i in q["issues"]:
        tag = {"high": "HIGH", "medium": "MEDIUM", "low": "LOW", "info": "NOTE"}[i["severity"]]
        L.append(f"- **{tag}:** {i['text']}")
    L.append("")

    if t:
        L.append(f"## 3. What Is Associated With {t['name']}?")
        L.append(f"Ranked by {t['model']['ranking_basis']}. Each finding shows the evidence, how confident we are, "
                 "and what could weaken it.")
        L.append("")
        for f in facts["findings"]:
            L.append(f"**{f['id']}. {f['text']}**")
            L.append(f"- Evidence: {f['evidence']}")
            L.append(f"- Confidence: **{f['confidence']}**")
            if f["caveat"]:
                L.append(f"- Watch out: {f['caveat']}")
            L.append("")
        tiers = t.get("tiers")
        if tiers:
            L.append(f"**Tiers of {tiers['feature']}** (low / mid / high thirds of the rows):")
            for r in tiers["rows"]:
                L.append(f"- {r['tier']} ({g(r['x_min'])} to {g(r['x_max'])}): average {t['name']} = "
                         f"{g(r['mean'])} (n={r['n']})")
            L.append(f"- High minus Low gap: {g(tiers['gap'])} ({fmt_p(tiers['p'])})")
            L.append("")
        if t["performers"]:
            L.append(f"**Top vs bottom quartile of {t['name']}:** what best performers look like")
            for p in t["performers"]:
                L.append(f"- {p['name']}: {g(p['hi_mean'])} in the top quartile vs {g(p['lo_mean'])} in the "
                         f"bottom quartile (effect size d={sg(p['d'])})")
            L.append("")
        tt = facts.get("time_trend")
        if tt:
            L.append(f"**Trend over time:** {t['name']} is {tt['direction']} by {tt['period']}, from "
                     f"{g(tt['first'])} to {g(tt['last'])} ({tt['start']} to {tt['end']}, {fmt_p(tt['p'])}).")
            L.append("")
    else:
        L.append("## 3. Main Patterns In The Data")
        for p in facts["top_pairs"][:5]:
            L.append(f"- {p['a']} and {p['b']}: r={sg(p['r'])} ({fmt_p(p['p'])}, n={p['n']})")
        L.append("")

    others = [p for p in facts["top_pairs"]
              if not t or t["name"] not in (p["a"], p["b"])][:3]
    if others and t:
        L.append("**Other relationships between variables**")
        for p in others:
            L.append(f"- {p['a']} and {p['b']}: r={sg(p['r'])} ({fmt_p(p['p'])}, n={p['n']})")
        L.append("")

    L.append("## 4. Recommendations")
    L.append(sections["recommendations"])
    L.append("")

    L.append("## 5. Limits Of This Analysis")
    L.append(sections["limits"])
    for c in facts["caveats"]:
        if c not in sections["limits"]:
            L.append(f"- {c}")
    L.append("")

    L.append("## 6. How This Was Checked")
    L.append("- All statistics were computed with pandas, SciPy and scikit-learn, not by the AI.")
    L.append("- Methods: Pearson and Spearman correlation, standardized multiple regression (with overlap/VIF check), "
             "cross-validated random-forest permutation importance, Kruskal-Wallis group tests.")
    if verification.get("ai_used"):
        L.append(f"- The AI-written text was re-checked against the computed numbers: "
                 f"{verification['verified']} of {verification['checked']} figures matched"
                 + (f"; {verification['removed']} statement(s) with unverifiable figures or wrong direction "
                    f"were removed" if verification["removed"] else "") + ".")
    else:
        L.append("- The AI service was unavailable, so the summary above was generated by rules from the "
                 "verified numbers. " + (verification.get("error", "")[:120]))
    if extra_note:
        L.append(f"- {extra_note}")
    L.append("- Decision support only: correlation is not causation, and the file cannot show factors that were "
             "not recorded.")
    return "\n".join(L)


# --------------------------------------------------------------------------- PDF
_ASCII_MAP = {"\u2212": "-", "\u2013": "-", "\u2014": "-", "\u2018": "'", "\u2019": "'", "\u201c": '"',
              "\u201d": '"', "\u2022": "-", "\u2248": "~", "\u2265": ">=", "\u2264": "<=", "\u00d7": "x",
              "\u00b1": "+/-", "\u2192": "->", "\u03b2": "beta", "\u03c1": "rho", "\u03c3": "sd"}


def _ascii(text):
    for k, v in _ASCII_MAP.items():
        text = text.replace(k, v)
    return text.encode("latin-1", "replace").decode("latin-1")


def _register_fonts(pdf):
    """matplotlib ships DejaVu fonts - they support minus signs and symbols."""
    try:
        import matplotlib
        d = os.path.join(matplotlib.get_data_path(), "fonts", "ttf")
        files = {"": "DejaVuSans.ttf", "B": "DejaVuSans-Bold.ttf",
                 "I": "DejaVuSans-Oblique.ttf", "BI": "DejaVuSans-BoldOblique.ttf"}
        if all(os.path.exists(os.path.join(d, f)) for f in files.values()):
            for style, f in files.items():
                pdf.add_font("DejaVu", style, os.path.join(d, f))
            return "DejaVu"
    except Exception:
        pass
    return None


class _PDF(FPDF):
    def footer(self):
        self.set_y(-12)
        self.set_font(self.fam, "", 8)
        self.set_text_color(130, 130, 130)
        self.cell(0, 8, f"Page {self.page_no()}", align="C")
        self.set_text_color(0, 0, 0)


def _md_safe(text):
    text = text.replace("--", "-")
    if text.count("**") % 2:
        text = text.replace("**", "")
    if text.count("__") % 2:
        text = text.replace("__", "")
    return text


def _write_markdown(pdf, text, T, bullet):
    for raw in text.split("\n"):
        line = raw.rstrip()
        pdf.set_x(pdf.l_margin)
        if not line.strip():
            pdf.ln(2)
            continue
        if line.startswith("## "):
            pdf.ln(3)
            pdf.set_font(pdf.fam, "B", 12.5)
            pdf.set_fill_color(228, 239, 250)
            pdf.cell(0, 8, T(line[3:]), new_x="LMARGIN", new_y="NEXT", fill=True)
            pdf.set_font(pdf.fam, "", 10)
            pdf.ln(1)
        elif re.match(r"^\s*[-*]\s+", line):
            body = re.sub(r"^\s*[-*]\s+", "", line)
            pdf.set_x(pdf.l_margin + 4)
            w = pdf.w - pdf.r_margin - pdf.get_x()
            pdf.multi_cell(w, 5.2, T(_md_safe(f"{bullet} {body}")), markdown=True,
                           new_x="LMARGIN", new_y="NEXT", align="L")
        else:
            pdf.multi_cell(0, 5.4, T(_md_safe(line)), markdown=True, new_x="LMARGIN", new_y="NEXT", align="L")


def save_report_as_pdf(report_md, charts, dataset_name, out_dir):
    """Create the PDF. Returns the file path (or None on failure)."""
    try:
        from PIL import Image

        pdf = _PDF(format="A4")
        fam = _register_fonts(pdf)
        unicode_ok = fam is not None
        pdf.fam = fam or "Helvetica"
        T = (lambda s: s) if unicode_ok else _ascii
        bullet = "\u2022" if unicode_ok else "-"

        pdf.set_margins(15, 15, 15)
        pdf.set_auto_page_break(auto=True, margin=18)
        pdf.add_page()

        # title banner
        pdf.set_font(pdf.fam, "B", 20)
        pdf.set_fill_color(31, 78, 121)
        pdf.set_text_color(255, 255, 255)
        pdf.cell(0, 14, "Data Analysis Report", align="C", new_x="LMARGIN", new_y="NEXT", fill=True)
        pdf.set_text_color(0, 0, 0)
        pdf.ln(3)
        pdf.set_font(pdf.fam, "", 10)
        _write_markdown(pdf, report_md, T, bullet)

        # charts
        if charts:
            pdf.add_page()
            pdf.set_font(pdf.fam, "B", 15)
            pdf.set_fill_color(31, 78, 121)
            pdf.set_text_color(255, 255, 255)
            pdf.cell(0, 11, "Charts", align="C", new_x="LMARGIN", new_y="NEXT", fill=True)
            pdf.set_text_color(0, 0, 0)
            pdf.ln(3)
            usable_w = pdf.w - pdf.l_margin - pdf.r_margin
            for i, c in enumerate(charts, 1):
                with Image.open(c["path"]) as im:
                    iw, ih = im.size
                img_w = min(usable_w, 138)
                img_h = img_w * ih / iw
                max_h = pdf.h - 110
                if img_h > max_h:
                    img_w, img_h = img_w * max_h / img_h, max_h
                need = img_h + 36
                if pdf.get_y() + need > pdf.h - 18:
                    pdf.add_page()
                pdf.set_x(pdf.l_margin)
                pdf.set_font(pdf.fam, "B", 11.5)
                pdf.multi_cell(0, 6, T(f"Chart {i}: {c['title']}"), new_x="LMARGIN", new_y="NEXT")
                pdf.set_font(pdf.fam, "I", 9)
                pdf.set_text_color(70, 70, 70)
                pdf.multi_cell(0, 4.8, T("What it shows: " + c["aim"]), new_x="LMARGIN", new_y="NEXT", align="L")
                pdf.set_text_color(0, 0, 0)
                y0 = pdf.get_y() + 1
                pdf.image(c["path"], x=pdf.l_margin + (usable_w - img_w) / 2, y=y0, w=img_w)
                pdf.set_y(y0 + img_h + 2)
                pdf.set_font(pdf.fam, "", 9.5)
                pdf.set_x(pdf.l_margin)
                pdf.multi_cell(0, 5, T(_md_safe("**So what:** " + c["so_what"])), markdown=True,
                               new_x="LMARGIN", new_y="NEXT", align="L")
                pdf.ln(5)

        os.makedirs(out_dir, exist_ok=True)
        safe = "".join(ch for ch in dataset_name if ch.isalnum() or ch in " -_")[:30] or "analysis"
        path = os.path.join(out_dir, f"report_{safe}.pdf")
        pdf.output(path)
        return path
    except Exception as e:  # noqa
        print(f"PDF generation failed: {e}")
        return None
